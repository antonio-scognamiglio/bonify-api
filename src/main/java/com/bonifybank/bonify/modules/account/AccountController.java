package com.bonifybank.bonify.modules.account;

import java.util.List;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import com.bonifybank.bonify.config.ApiExamples;
import com.bonifybank.bonify.config.OpenApiConfig;
import com.bonifybank.bonify.exception.dto.ErrorResponse;
import com.bonifybank.bonify.modules.account.dto.AccountResponse;
import com.bonifybank.bonify.modules.account.dto.CashOperationRequest;
import com.bonifybank.bonify.modules.account.dto.UpdateAccountStatusRequest;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.ArraySchema;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.ExampleObject;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import lombok.RequiredArgsConstructor;

@RestController
@RequestMapping("/accounts")
@Validated
@RequiredArgsConstructor
@Tag(name = OpenApiConfig.TAG_ACCOUNTS)
public class AccountController {

    private static final String IBAN_DESCRIPTION = "IBAN of the account, as returned when it was opened";

    private final AccountService accountService;

    // FR-ACC-01: no body, opens an EUR account owned by the caller, returns 201
    @Operation(summary = "Open an account", description = """
            Opens a new EUR current account owned by the caller, with balance 0 and status `ACTIVE`.
            No request body: the IBAN is generated by the server. A customer can own several accounts.
            """)
    @ApiResponse(responseCode = "201", description = "Account opened",
            content = @Content(mediaType = ApiExamples.JSON, schema = @Schema(implementation = AccountResponse.class),
                    examples = @ExampleObject(value = ApiExamples.NEW_ACCOUNT)))
    @ApiResponse(responseCode = "403", description = "Caller is not a customer (e.g. the admin)",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.FORBIDDEN_ROLE)))
    @PreAuthorize("hasRole('CUSTOMER')")
    @PostMapping(version = "1+")
    public ResponseEntity<AccountResponse> openAccount() {
        return ResponseEntity.status(HttpStatus.CREATED).body(accountService.openAccount());
    }

    // FR-ACC-02: all the caller's accounts
    @Operation(summary = "List my accounts", description = "All the accounts of the caller (empty list if none).")
    @ApiResponse(responseCode = "200", description = "Own accounts",
            content = @Content(mediaType = ApiExamples.JSON,
                    array = @ArraySchema(schema = @Schema(implementation = AccountResponse.class)),
                    examples = @ExampleObject(value = ApiExamples.ACCOUNT_LIST)))
    @ApiResponse(responseCode = "403", description = "Caller is not a customer",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.FORBIDDEN_ROLE)))
    @PreAuthorize("hasRole('CUSTOMER')")
    @GetMapping(version = "1+")
    public ResponseEntity<List<AccountResponse>> listMyAccounts() {
        return ResponseEntity.ok(accountService.listMyAccounts());
    }

    // FR-ACC-03: owner or admin (ownership is checked by the service)
    @Operation(summary = "Get an account", description = "Detail and current balance. Owner or admin only.")
    @ApiResponse(responseCode = "200", description = "Account detail",
            content = @Content(mediaType = ApiExamples.JSON, schema = @Schema(implementation = AccountResponse.class),
                    examples = @ExampleObject(value = ApiExamples.ACCOUNT)))
    @ApiResponse(responseCode = "403", description = "The account belongs to another customer",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.FORBIDDEN_ACCOUNT)))
    @ApiResponse(responseCode = "404", description = "Unknown IBAN",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.ACCOUNT_NOT_FOUND)))
    @PreAuthorize("hasAnyRole('CUSTOMER', 'ADMIN')")
    @GetMapping(path = "/{iban}", version = "1+")
    public ResponseEntity<AccountResponse> getAccount(
            @Parameter(description = IBAN_DESCRIPTION, example = ApiExamples.IBAN) @PathVariable String iban) {
        return ResponseEntity.ok(accountService.getAccount(iban));
    }

    // FR-ACC-04: owner only, account must be ACTIVE
    @Operation(summary = "Deposit", description = """
            Adds cash to an own `ACTIVE` account and records a `DEPOSIT` movement.
            Returns the account with the new balance.
            """)
    @ApiResponse(responseCode = "200", description = "Deposit done, new balance",
            content = @Content(mediaType = ApiExamples.JSON, schema = @Schema(implementation = AccountResponse.class),
                    examples = @ExampleObject(value = ApiExamples.ACCOUNT)))
    @ApiResponse(responseCode = "400", description = "Invalid amount or description",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.VALIDATION_ERROR_AMOUNT)))
    @ApiResponse(responseCode = "403", description = "The account belongs to another customer",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.FORBIDDEN_ACCOUNT)))
    @ApiResponse(responseCode = "404", description = "Unknown IBAN",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.ACCOUNT_NOT_FOUND)))
    @ApiResponse(responseCode = "422", description = "The account is BLOCKED",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.ACCOUNT_BLOCKED)))
    @PreAuthorize("hasRole('CUSTOMER')")
    @PostMapping(path = "/{iban}/deposit", version = "1+")
    public ResponseEntity<AccountResponse> deposit(
            @Parameter(description = IBAN_DESCRIPTION, example = ApiExamples.IBAN) @PathVariable String iban,
            @Validated @RequestBody CashOperationRequest request) {
        return ResponseEntity.ok(accountService.deposit(iban, request));
    }

    // FR-ACC-05: owner only, account must be ACTIVE, balance cannot go negative
    @Operation(summary = "Withdraw", description = """
            Takes cash from an own `ACTIVE` account and records a `WITHDRAW` movement.
            The balance can never go below zero.
            """)
    @ApiResponse(responseCode = "200", description = "Withdrawal done, new balance",
            content = @Content(mediaType = ApiExamples.JSON, schema = @Schema(implementation = AccountResponse.class),
                    examples = @ExampleObject(value = ApiExamples.ACCOUNT)))
    @ApiResponse(responseCode = "400", description = "Invalid amount or description",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.VALIDATION_ERROR_AMOUNT)))
    @ApiResponse(responseCode = "403", description = "The account belongs to another customer",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.FORBIDDEN_ACCOUNT)))
    @ApiResponse(responseCode = "404", description = "Unknown IBAN",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.ACCOUNT_NOT_FOUND)))
    @ApiResponse(responseCode = "422", description = "Insufficient funds, or the account is BLOCKED",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = {
                            @ExampleObject(name = "INSUFFICIENT_FUNDS", value = ApiExamples.INSUFFICIENT_FUNDS),
                            @ExampleObject(name = "ACCOUNT_BLOCKED", value = ApiExamples.ACCOUNT_BLOCKED)
                    }))
    @PreAuthorize("hasRole('CUSTOMER')")
    @PostMapping(path = "/{iban}/withdraw", version = "1+")
    public ResponseEntity<AccountResponse> withdraw(
            @Parameter(description = IBAN_DESCRIPTION, example = ApiExamples.IBAN) @PathVariable String iban,
            @Validated @RequestBody CashOperationRequest request) {
        return ResponseEntity.ok(accountService.withdraw(iban, request));
    }

    // FR-ACC-06: block or unblock an account
    @Operation(summary = "Block or unblock an account (admin)", description = """
            Sets the status to `BLOCKED` or `ACTIVE`. A blocked account keeps its balance and can still be
            read, but deposits, withdrawals and transfers from or to it are refused with 422 `ACCOUNT_BLOCKED`.
            """)
    @ApiResponse(responseCode = "200", description = "Status updated",
            content = @Content(mediaType = ApiExamples.JSON, schema = @Schema(implementation = AccountResponse.class),
                    examples = @ExampleObject(value = ApiExamples.BLOCKED_ACCOUNT)))
    @ApiResponse(responseCode = "400", description = "Status other than ACTIVE or BLOCKED",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.VALIDATION_ERROR_STATUS)))
    @ApiResponse(responseCode = "403", description = "Caller is not an admin",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.FORBIDDEN_ROLE)))
    @ApiResponse(responseCode = "404", description = "Unknown IBAN",
            content = @Content(mediaType = ApiExamples.PROBLEM_JSON,
                    schema = @Schema(implementation = ErrorResponse.class),
                    examples = @ExampleObject(value = ApiExamples.ACCOUNT_NOT_FOUND)))
    @PreAuthorize("hasRole('ADMIN')")
    @PatchMapping(path = "/{iban}/status", version = "1+")
    public ResponseEntity<AccountResponse> updateStatus(
            @Parameter(description = IBAN_DESCRIPTION, example = ApiExamples.IBAN) @PathVariable String iban,
            @Validated @RequestBody UpdateAccountStatusRequest request) {
        return ResponseEntity.ok(accountService.updateStatus(iban, request));
    }
}
